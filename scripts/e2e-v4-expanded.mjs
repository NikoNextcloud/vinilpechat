import assert from 'node:assert/strict';
import {mkdirSync} from 'node:fs';
import {chromium} from 'playwright';
mkdirSync('test-output',{recursive:true});
const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:1400,height:850}});
page.setDefaultTimeout(20000);
const errors=[];page.on('pageerror',e=>errors.push(e.message));
const base='http://127.0.0.1:3000',goto=p=>page.goto(base+p,{waitUntil:'domcontentloaded'});
try{
 await goto('/pechatni-produkti/');
 await page.locator('.vp-card').first().waitFor();
 assert.equal(await page.locator('.vp-card').count(),38);
 assert.equal(await page.locator('.vp-group').count(),5);
 await page.screenshot({path:'test-output/v4-extended-catalog-desktop.png',fullPage:false});
 await page.locator('#vp-search').fill('рол банер');
 assert((await page.locator('.vp-card').count())>=2);
 await page.locator('#vp-search').fill('');
 await page.locator('.vp-group[data-group="Печатни материали"]').click();
 assert((await page.locator('.vp-card').count())>=8);
 await page.locator('.vp-group[data-group="all"]').click();
 await page.locator('.vp-card[data-service="VP4-013"] .vp-add').click();
 assert.equal(await page.locator('[data-v4-quote-count]').first().innerText(),'1');
 await page.setViewportSize({width:390,height:844});
 const measure=await page.evaluate(()=>({scroll:document.documentElement.scrollWidth,viewport:innerWidth}));
 assert(measure.scroll<=measure.viewport+5,'mobile page overflow '+JSON.stringify(measure));
 await page.screenshot({path:'test-output/v4-extended-catalog-mobile.png',fullPage:false});
 await page.setViewportSize({width:1400,height:850});
 await goto('/teniski/#model-ST2300');
 await page.locator('#detail-code').waitFor({state:'visible'});
 await page.locator('#v4-shirt-add').click();
 assert((await page.locator('#message-hint').innerText()).includes('добавена'));
 await goto('/#design');
 await page.locator('#v4AddInquiry').waitFor({state:'visible'});
 await page.waitForFunction(()=>document.querySelector('#designTotal')?.textContent?.includes('€'),null,{timeout:20000});
 await page.locator('#v4AddInquiry').click();
 assert((await page.locator('#toast').innerText()).includes('добавен'));
 await goto('/#catalog');
 await page.locator('[data-v4-add-material]').first().waitFor({state:'visible'});
 await page.locator('[data-v4-add-material]').first().click();
 await goto('/zapitvane/');
 await page.locator('.vp-item').first().waitFor();
 assert.equal(await page.locator('.vp-item').count(),4);
 assert(await page.locator('#vp-submit').isDisabled(),'Unconfigured checkout must not submit');
 await page.screenshot({path:'test-output/v4-combined-inquiry.png',fullPage:false});
 // Mock payment-free submission; no real order or customer data is ever sent.
 await page.route('**/api/health',route=>route.fulfill({status:200,contentType:'application/json',body:JSON.stringify({ok:true,ordersReady:true})}));
 let posted=null;
 await page.route('**/api/orders',async route=>{
  posted=route.request().postDataJSON();
  await route.fulfill({status:201,contentType:'application/json',body:JSON.stringify({ok:true,order_id:'DEMO-V4'})});
 });
 await page.reload({waitUntil:'domcontentloaded'});
 await page.waitForFunction(()=>!document.querySelector('#vp-submit').disabled);
 await page.locator('input[name=name]').fill('Тест Клиент');
 await page.locator('input[name=phone]').fill('0888000000');
 await page.locator('#vp-submit').click();
 await page.locator('#vp-confirm:not([hidden])').waitFor();
 assert(posted?.kind==='contact');
 assert(posted.message.includes('Рол банер'));
 assert(posted.message.includes('Тениска ST2300'));
 assert(posted.message.includes('Печат на винил по размер'));
 assert(posted.message.includes('Материал'));
 assert.equal(await page.locator('.vp-item').count(),0);
 assert.deepEqual(errors,[]);
 console.log('VINILPECHAT_V4_EXTENDED_QUOTE_PASS',JSON.stringify({services:38,groups:4,mixedQuote:true,apiMocked:true,mobile:true,errors:0}));
}finally{await browser.close();}
