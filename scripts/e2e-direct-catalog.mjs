import assert from 'node:assert/strict';
import {mkdirSync} from 'node:fs';
import {chromium} from 'playwright';
mkdirSync('test-output',{recursive:true});
const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:1440,height:900}});
page.setDefaultTimeout(16000);
const jsErrors=[];
page.on('pageerror',e=>jsErrors.push(e.message));
const base='http://127.0.0.1:3000';
const requested='/teniski/'+encodeURIComponent('Мъжка тениска')+'-model-ST2300';
try{
 let response=await page.goto(base+'/brezenti/',{waitUntil:'domcontentloaded'});
 assert.equal(response.status(),200,'Cover listing response');
 await page.locator('.cover-product').first().waitFor({state:'visible'});
 assert((await page.locator('.cover-product').count())>0,'Cover products load directly');
 assert.equal(await page.locator('.hero a.btn').count(),0,'old buttons removed');
 const photos=await page.locator('.cover-product img').count();
 assert(photos>0,'cover catalog shows product photos');
 await page.screenshot({path:'test-output/v3-covers-catalog-desktop.png',fullPage:true});
 await page.locator('#cover-search').fill('кристал');
 assert((await page.locator('.cover-product').count())>0,'search filters real catalog');
 await page.locator('#cover-search').fill('');
 await page.locator('#cover-category').selectOption('tir');
 assert((await page.locator('.cover-product').count())>0,'category filter works');
 await page.locator('#cover-category').selectOption('all');
 const firstLink=await page.locator('.cover-product a.cover-open').first().getAttribute('href');
 assert(firstLink.startsWith('/#item-'),'catalog opens existing product details');
 await page.setViewportSize({width:390,height:844});
 const coversWidth=await page.evaluate(()=>({width:document.documentElement.scrollWidth,viewport:innerWidth}));
 assert(coversWidth.width<=coversWidth.viewport+5,'cover catalog has no mobile horizontal overflow '+JSON.stringify(coversWidth));
 await page.screenshot({path:'test-output/v3-covers-catalog-mobile.png',fullPage:true});
 await page.setViewportSize({width:1440,height:900});
 response=await page.goto(base+requested,{waitUntil:'domcontentloaded'});
 assert.equal(response.status(),200,'direct ST2300 SSR route returns 200');
 await page.locator('#detail-code').waitFor({state:'visible'});
 assert.equal(await page.locator('#detail-code').innerText(),'ST2300');
 assert.equal(new URL(page.url()).pathname,requested,'requested URL stays canonical');
 assert((await page.title()).includes('ST2300'),'per-model title');
 const canonical=await page.locator('link[rel="canonical"]').getAttribute('href');
 assert(canonical.endsWith(requested),'per-model canonical URL');
 await page.screenshot({path:'test-output/v3-shirt-st2300-direct.png',fullPage:true});
 await page.locator('#back-to-models').click();
 assert.equal(new URL(page.url()).pathname,'/teniski/','back to model catalog resets URL');
 await page.locator('[data-model="ST2300"]').click();
 assert.equal(new URL(page.url()).pathname,requested,'click from catalog updates address');
 await page.goto(base+'/teniski/#model-ST2300',{waitUntil:'domcontentloaded'});
 await page.locator('#detail-code').waitFor({state:'visible'});
 assert.equal(await page.locator('#detail-code').innerText(),'ST2300','old hash deep links still work');
 assert.deepEqual(jsErrors,[],'no browser JS errors');
 console.log('COVER_CATALOG_AND_SHIRT_LINKS_PASS',JSON.stringify({covers:true,search:true,filters:true,mobile:true,shirtUrl:requested,oldHash:true}));
}finally{await browser.close();}
