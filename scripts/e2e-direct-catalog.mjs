import assert from 'node:assert/strict';
import {mkdirSync} from 'node:fs';
import {chromium} from 'playwright';
mkdirSync('test-output',{recursive:true});
const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:1440,height:900}});
page.setDefaultTimeout(20000);
const errors=[];
page.on('pageerror',error=>errors.push(error.message));
const base='http://127.0.0.1:3000';
const shirt='/teniski/'+encodeURIComponent('Мъжка тениска')+'-model-ST2300';
try{
 let response=await page.goto(base+'/brezenti/',{waitUntil:'domcontentloaded'});
 assert.equal(response.status(),200);
 const cards=page.locator('.cover-product');
 await cards.first().waitFor({state:'visible'});
 assert((await cards.count())>=3,'Catalog loads at least three cards');
 assert((await page.locator('[data-cover-cat]').count())>=8,'Full left category sidebar loads');
 assert(await page.locator('#cover-search').isVisible(),'Search visible');
 assert(await page.locator('#cover-sort').isVisible(),'Sort visible');
 assert.equal(await page.locator('.hero a.btn').count(),0,'Old promotional buttons are absent');
 const boxes=await Promise.all([0,1,2].map(i=>cards.nth(i).boundingBox()));
 assert(boxes.every(Boolean),'First three cards visible');
 assert(Math.abs(boxes[0].y-boxes[1].y)<3&&Math.abs(boxes[1].y-boxes[2].y)<3,'Three cards share first row');
 assert(boxes[0].x<boxes[1].x&&boxes[1].x<boxes[2].x,'Three desktop columns');
 const overlap=async()=>{
  const values=await cards.first().evaluate(el=>{
   const image=el.querySelector('.cover-photo').getBoundingClientRect();
   const category=el.querySelector('.cover-product-category').getBoundingClientRect();
   const title=el.querySelector('.cover-product-title').getBoundingClientRect();
   const description=el.querySelector('.cover-product-desc').getBoundingClientRect();
   return {photoBottom:image.bottom,categoryTop:category.top,titleTop:title.top,titleBottom:title.bottom,descriptionTop:description.top};
  });
  assert(values.categoryTop>=values.photoBottom-2,'Category text must be below image '+JSON.stringify(values));
  assert(values.titleTop>=values.photoBottom-2,'Title must not overlap photo '+JSON.stringify(values));
  assert(values.descriptionTop>=values.titleBottom-2,'Description must be below title '+JSON.stringify(values));
 };
 await overlap();
 const firstProductId=await cards.first().getAttribute('data-product-id');
 const href=await cards.first().locator('.cover-product-title').getAttribute('href');
 assert.match(href,/^\/produkti\/\d+-[a-z0-9-]+$/,'Latin SEO product links');
 assert(!href.includes('#item'),'Legacy hash not shown in links');
 await page.screenshot({path:'test-output/v3-covers-catalog-desktop.png',fullPage:true});
 await page.locator('#cover-search').fill('кристал');
 assert((await cards.count())>0,'Search works');
 await page.locator('#cover-search').fill('');
 await page.locator('[data-cover-cat="tir"]').click();
 assert((await cards.count())>0,'Sidebar category filter works');
 assert.equal(await page.locator('[data-cover-cat="tir"]').getAttribute('aria-pressed'),'true');
 await page.locator('[data-cover-cat="all"]').click();
 await page.locator('#cover-sort').selectOption('name');
 assert((await cards.count())>3,'Sort preserves catalogue');
 await page.locator('#cover-sort').selectOption('default');
 const simple=page.locator('.cover-product').filter({has:page.locator('button.cover-add:text-is("+ Добави")')}).first();
 assert(await simple.count(),'Direct add-to-cart available for simple products');
 const cartId=await simple.getAttribute('data-product-id');
 await simple.locator('button.cover-add').click();
 const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('vinyl-cart')||'[]'));
 assert(saved.some(x=>String(x.id)===String(cartId)),'Cart is shared with main shop');
 await page.setViewportSize({width:390,height:844});
 await overlap();
 const w=await page.evaluate(()=>({scroll:document.documentElement.scrollWidth,viewport:innerWidth}));
 assert(w.scroll<=w.viewport+5,'Mobile page must not overflow horizontally '+JSON.stringify(w));
 await page.screenshot({path:'test-output/v3-covers-catalog-mobile.png',fullPage:true});
 await page.setViewportSize({width:1440,height:900});
 // Clicking a cover photo opens the existing interactive product dialog, not an inert static screen.
 const coverUrl=await cards.first().locator('.cover-photo').getAttribute('href');
 await cards.first().locator('.cover-photo').click();
 await page.locator('#productDialog').waitFor({state:'visible'});
 assert.equal(new URL(page.url()).pathname,coverUrl,'Cover product keeps SEO-friendly pathname inside dialog');
 await page.locator('#productClose').click();
 await page.goto(base+'/#catalog',{waitUntil:'domcontentloaded'});
 const modalLink=page.locator('a.product-photo[data-detail="13"]');
 await modalLink.waitFor({state:'visible'});
 const expected='/produkti/13-lenta-kristal-za-vrati-2000-mikrona';
 assert.equal(await modalLink.getAttribute('href'),expected);
 await modalLink.click();
 await page.locator('#productDialog').waitFor({state:'visible'});
 assert.equal(new URL(page.url()).pathname,expected,'Opening modal updates to SEO permalink');
 assert((await page.locator('#productDetail h2').innerText()).includes('Лента кристал'));
 await page.screenshot({path:'test-output/v3-canonical-product-modal.png',fullPage:true});
 await page.locator('#productClose').click();
 assert.equal(new URL(page.url()).pathname,'/','Closing modal restores catalog URL');
 await page.goto(base+'/#item-13',{waitUntil:'domcontentloaded'});
 await page.locator('#productDialog').waitFor({state:'visible'});
 assert.equal(new URL(page.url()).pathname,expected,'Old hash link upgrades to SEO permalink');
 await page.goto(base+shirt,{waitUntil:'domcontentloaded'});
 await page.locator('#detail-code').waitFor({state:'visible'});
 assert.equal(await page.locator('#detail-code').innerText(),'ST2300');
 assert.equal(new URL(page.url()).pathname,shirt);
 await page.locator('#back-to-models').click();
 assert.equal(new URL(page.url()).pathname,'/teniski/');
 await page.locator('[data-model="ST2300"]').click();
 assert.equal(new URL(page.url()).pathname,shirt);
 assert.deepEqual(errors,[],'Browser JavaScript errors');
 console.log('VINILPECHAT_PRODUCT_URL_AND_COVER_CATALOG_PASS',JSON.stringify({sidebar:true,threeColumns:true,noOverlap:true,mobile:true,cart:true,seoProductUrl:expected,shirts:true,jsErrors:0}));
}finally{await browser.close();}
